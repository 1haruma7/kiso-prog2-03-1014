// & とマスクで、下位4ビットだけを取り出す
//
// やってみよう：
//   ① 上位4ビット（左の4つ）だけを取り出すには、filter をどう変える？ 予想してから確かめる
//   ② filter を変えて、1の位のビット（一番右）だけを取り出す。偶数・奇数の判定に使えるか考える
#include <stdio.h>

int main(void)
{
    int a = 0b01101100;
    int filter = 0b00001111;

    printf("%d\n", a & filter);   /* 2進数で0000 1100 */
    return 0;
}
