// 左シフトで1ビットずつ左にずらし、値がどう変わるかを確かめる
//
// やってみよう：
//   ① 実行する前に、3つの表示を予想する
//   ② a を 5 に変えて、a << 4 の結果を予想してから確かめる
//   ③ 整数を scanf で入力し、8倍した値を表示するように書き換える（* は使わない）
#include <stdio.h>

int main(void)
{
    int a = 0b00000011;   /* 10進数で3 */

    printf("%d\n", a << 1);
    printf("%d\n", a << 2);
    printf("%d\n", a << 3);
    return 0;
}
