// 同じビット列 1111 1100 を、符号付きと符号なしで右シフトしたときの違いを確かめる
//
// やってみよう：
//   ① 実行する前に、2つの表示を予想する（スライドの表と見比べる）
//   ② s を -5 に変えて、s >> 1 と s / 2 を並べて表示する。結果は同じ？
#include <stdio.h>

int main(void)
{
    signed char s = -4;      /* 1111 1100 */
    unsigned char u = 252;   /* 1111 1100 */

    printf("%d %d\n", s >> 2, u >> 2);
    return 0;
}
