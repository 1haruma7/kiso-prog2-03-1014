// & で最上位ビットだけを取り出し、正の数か負の数かを判定する
//
// やってみよう：
//   ① 5、-5、127、-128 を入力して、判定が正しいか確かめる
//   ② 0 を入力すると、どちらと表示される？ 理由を説明してみよう
//   ③ 0b10000000 を 0b00000001 に変えると、何を判定するプログラムになる？
#include <stdio.h>

int main(void)
{
    signed char d;

    printf("整数=");
    scanf("%hhd", &d);   /* %hhd は1バイトの整数（signed char）を読む書式 */

    if ((d & 0b10000000) == 0) {
        printf("正の数です\n");
    } else {
        printf("負の数です\n");
    }
    return 0;
}
